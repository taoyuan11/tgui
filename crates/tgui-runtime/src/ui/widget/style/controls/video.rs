use super::*;

#[derive(Clone, Debug, PartialEq)]
pub struct VideoStyle {
    pub surface: WidgetSurfaceStyle,
    pub background: Value<Color>,
    pub border: Value<Color>,
    pub border_width: Dp,
    pub radius: Dp,
    pub padding: Insets,
    pub gap: Dp,
    pub controls_gap: Dp,
    pub overlay_background: Value<Color>,
    pub overlay_padding: Insets,
    pub overlay_gap: Dp,
    pub default_surface_width: Dp,
    pub default_surface_height: Dp,
    pub progress_height: Dp,
    pub progress_hit_height: Dp,
    pub progress_track_color: Value<Color>,
    pub progress_buffered_color: Value<Color>,
    pub progress_active_color: Value<Color>,
    pub progress_thumb_color: Value<Color>,
    pub volume_width: Dp,
    pub playback_rate_width: Dp,
    pub audio_track_width: Dp,
    pub subtitle_track_width: Dp,
    pub control_button_size: Dp,
    pub control_icon_size: Dp,
    pub control_icon_color: Value<Color>,
    pub control_icon_disabled_color: Value<Color>,
    pub control_disabled_opacity: f32,
    pub time_text_color: Value<Color>,
    pub status_text_color: Value<Color>,
    pub status_background: Value<Color>,
    pub status_padding: Insets,
    pub subtitle_text_color: Value<Color>,
    pub subtitle_background: Value<Color>,
    pub subtitle_padding: Insets,
    pub subtitle_bottom_offset: Dp,
    pub time_text_style: TextStyle,
    pub status_text_style: TextStyle,
    pub subtitle_text_style: TextStyle,
}

impl VideoStyle {
    pub fn default_for_theme(theme: &Theme) -> Self {
        let metrics = control_density_metrics(theme, theme.density);
        Self {
            surface: WidgetSurfaceStyle::default(),
            background: Value::Static(theme.colors.surface_low),
            border: Value::Static(theme.colors.outline_muted),
            border_width: theme.border.thin,
            radius: theme.radius.lg,
            padding: Insets::ZERO,
            gap: theme.spacing.sm,
            controls_gap: theme.spacing.xs,
            overlay_background: Value::Static(theme.colors.surface),
            overlay_padding: Insets::symmetric(
                theme.spacing.sm + theme.spacing.xs,
                theme.spacing.sm,
            ),
            overlay_gap: theme.spacing.xs,
            default_surface_width: dp(480.0),
            default_surface_height: dp(270.0),
            progress_height: theme.spacing.xs,
            progress_hit_height: theme.spacing.lg,
            progress_track_color: Value::Static(theme.colors.surface_high),
            progress_buffered_color: Value::Static(theme.colors.outline),
            progress_active_color: Value::Static(theme.colors.primary),
            progress_thumb_color: Value::Static(theme.colors.primary),
            volume_width: dp(160.0),
            playback_rate_width: dp(176.0),
            audio_track_width: dp(176.0),
            subtitle_track_width: dp(176.0),
            control_button_size: metrics.control_height,
            control_icon_size: theme.spacing.md + theme.spacing.xs,
            control_icon_color: Value::Static(theme.colors.on_surface),
            control_icon_disabled_color: Value::Static(theme.colors.on_disabled),
            control_disabled_opacity: 0.6,
            time_text_color: Value::Static(theme.colors.on_surface),
            status_text_color: Value::Static(theme.colors.on_surface),
            status_background: Value::Static(theme.colors.surface),
            status_padding: Insets::symmetric(theme.spacing.sm, theme.spacing.xs),
            subtitle_text_color: Value::Static(theme.colors.on_surface),
            subtitle_background: Value::Static(theme.colors.surface),
            subtitle_padding: Insets::symmetric(theme.spacing.sm, theme.spacing.xs),
            subtitle_bottom_offset: theme.spacing.md,
            time_text_style: theme.typography.label_small.clone(),
            status_text_style: theme.typography.label_small.clone(),
            subtitle_text_style: theme.typography.body_small.clone(),
        }
    }
}
